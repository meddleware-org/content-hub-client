import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'

import { check, count, fillIntent, IntentError, limitsForTarget, limitsFromDefinition, renderSource, segment } from '../src/index.js'
import type { Vectors } from '../src/vectors.js'

const vectors = JSON.parse(readFileSync(new URL('../vectors.json', import.meta.url), 'utf8')) as Vectors

describe('golden vectors (generated by the Rust implementation)', () => {
  it('has every section filled', () => {
    expect(vectors.counting.length).toBeGreaterThan(0)
    expect(vectors.rendering.length).toBeGreaterThan(0)
    expect(vectors.segmentation.length).toBeGreaterThan(0)
    expect(vectors.limits.length).toBeGreaterThan(0)
  })

  it.each(vectors.counting.map((v, i) => [i, v] as const))('counting #%i', (_i, v) => {
    expect(count({ method: v.method, urlWeight: v.url_weight, mentionLocalPart: v.mention_local_part }, v.text)).toBe(v.count)
  })

  it.each(vectors.rendering.map((v, i) => [i, v] as const))('rendering #%i', (_i, v) => {
    const r = renderSource(v.markup, v.source)
    expect(r.payload).toBe(v.payload)
    expect(r.visible).toBe(v.visible)
  })

  it.each(vectors.segmentation.map((v, i) => [i, v] as const))('segmentation #%i', (_i, v) => {
    const seg = segment(
      v.source,
      v.targets.map((t) => ({ id: t.id, markup: t.markup, limits: { rules: { method: t.method }, primary: t.limit } })),
    )
    expect(seg.cuts).toEqual(v.cuts)
    expect(seg.bands).toEqual(v.bands)
  })

  it.each(vectors.limits.map((v, i) => [i, v] as const))('limits and check #%i', (_i, v) => {
    const i = v.input
    const base = limitsFromDefinition({
      counting_method: i.counting_method,
      primary_limit: i.primary_limit,
      secondary_limits: i.secondary_limits,
    })
    const limits = limitsForTarget(base, i.secondary_limits, i.target_config)
    if (v.result.limits === null) {
      expect(limits).toBeNull()
      expect(renderSource(i.markup, i.body).payload).toBe(v.result.payload)
      return
    }
    const want = v.result.limits
    expect(limits).not.toBeNull()
    expect(limits!.rules.method).toBe(want.method)
    expect(limits!.rules.urlWeight ?? null).toBe(want.url_weight)
    expect(limits!.rules.mentionLocalPart ?? false).toBe(want.mention_local_part)
    expect(limits!.primary ?? null).toBe(want.primary)
    expect(limits!.bytes ?? null).toBe(want.bytes)
    expect(limits!.title ?? null).toBe(want.title)
    const c = check(i.markup, limits!, i.title, i.body)
    expect(c.payload).toBe(v.result.payload)
    expect(c.counted).toBe(v.result.counted)
    expect(c.bytes).toBe(v.result.bytes)
    expect(c.titleCounted).toBe(v.result.title_counted)
    expect(c.fits).toBe(v.result.fits)
  })
})

describe('intent links', () => {
  it('percent-encodes values and validates the base', () => {
    expect(fillIntent('https://x.com/intent/tweet?text={text}&url={url}', { text: 'Hello & welcome #1', url: 'https://example.org/a?b=c' })).toBe(
      'https://x.com/intent/tweet?text=Hello%20%26%20welcome%20%231&url=https%3A%2F%2Fexample.org%2Fa%3Fb%3Dc',
    )
    expect(() => fillIntent('{target_base}/x', { target_base: 'javascript:alert(1)' })).toThrow(IntentError)
  })
})
